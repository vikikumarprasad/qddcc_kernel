"""Evaluate saved water-CV winners on the target test splits used in Figure 5.

This reuses the recorded classical cross-validation scores; no target data enter
the C/epsilon selection. Comparing gamma values on the targets is retrospective.
The quantum rows summarize the completed, separately recorded gamma experiment.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
import sklearn
from sklearn.metrics import r2_score
from sklearn.svm import SVR

from qk_common import load_water_scaled

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "Experiments/results/water_bandwidth"
ARTIFACTS = ROOT / "paper_results/experiments/water_bandwidth"
MOLS = ["Water", "Ammonia", "Methane", "Formaldehyde", "Ethylene", "Methanol", "Ethane"]


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def write_table(df):
    lines = [r"% Generated by Experiments/water_bandwidth.py",
             r"\begin{tabular}{lrrrrrr}", r"\toprule",
             r"Model & $\gamma$ & $C$ & $\epsilon$ & Water CV & Water test & Transfer \\",
             r"\midrule"]
    for row in df.itertuples():
        if row.Index == int((df.model == "Classical").sum()):
            lines.append(r"\midrule")
        name = "Classical" if row.model == "Classical" else "ZZFeatureMap"
        gamma = f"{row.gamma:g}" + (r"$^{*}$" if row.gamma_selected_by_water_cv else "")
        lines.append(f"{name} & {gamma} & {row.C:g} & {row.epsilon:g} & "
                     f"{row.water_cv_r2:.6f} & {row.water_test_r2:.6f} & "
                     f"{row.mean_transfer_test_r2:.6f} " + r"\\")
    lines.extend([r"\bottomrule", r"\end{tabular}"])
    table = ROOT / "paper_results/regenerated_tables/table_s8.tex"
    table.parent.mkdir(parents=True, exist_ok=True)
    table.write_text("\n".join(lines) + "\n")

    return table


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    ARTIFACTS.mkdir(parents=True, exist_ok=True)
    cv_path = ROOT / "Experiments/results/water_reproduction/classical_cv.csv"
    cv = pd.read_csv(cv_path)
    cv["gamma"] = cv.param_gamma.replace("auto", "0.2").astype(float)
    assert len(cv) == 120
    assert not cv.duplicated(["param_C", "param_epsilon", "gamma"]).any()
    winners = cv.loc[cv.groupby("gamma").mean_test_score.idxmax()].sort_values("gamma")
    source_winner = cv.loc[cv.mean_test_score.idxmax()]
    X, y = load_water_scaled(ROOT / "data", "Water", "train")
    test = {mol: load_water_scaled(ROOT / "data", mol, "test") for mol in MOLS}
    rows, summary = [], []
    for row in winners.itertuples():
        model = SVR(C=row.param_C, epsilon=row.param_epsilon, gamma=row.gamma).fit(X, y)
        key = f"classical_gamma{row.gamma:g}"
        joblib.dump(model, ARTIFACTS / f"{key}.joblib")
        scores = {}
        for mol, (xt, yt) in test.items():
            pred = model.predict(xt)
            assert len(pred) == len(yt) and np.isfinite(pred).all()
            score = float(r2_score(yt, pred))
            scores[mol] = score
            np.savez_compressed(ARTIFACTS / f"{key}_{mol}_test.npz", y_true=yt, y_pred=pred)
            rows.append({"gamma": row.gamma, "C": model.C, "epsilon": model.epsilon,
                         "water_cv_r2": row.mean_test_score, "molecule": mol,
                         "n_test": len(yt), "test_r2": score})
        result = {"model": "Classical", "gamma": row.gamma, "C": model.C,
                  "epsilon": model.epsilon, "water_cv_r2": row.mean_test_score,
                  "water_test_r2": scores["Water"],
                  "mean_transfer_test_r2": float(np.mean([scores[m] for m in MOLS[1:]])),
                  "gamma_selected_by_water_cv": bool(row.gamma == source_winner.gamma)}
        summary.append(result)
        print(result, flush=True)
    pd.DataFrame(rows).to_csv(OUT / "classical_test_scores.csv", index=False)

    # Check the Figure 5 baseline against its independent saved evaluation.
    baseline = pd.read_csv(ROOT / "Experiments/results/water_reproduction/classical_scores.csv")
    baseline = baseline[baseline.model == "source_cv"].set_index("molecule")
    selected = pd.DataFrame(rows).query("gamma == @source_winner.gamma").set_index("molecule")
    error = float(np.max(np.abs(selected.loc[MOLS, "test_r2"] - baseline.loc[MOLS, "test_r2"])))
    assert error < 1e-12, error

    quantum_paths = [
        ROOT / "Experiments/results/water_reproduction/zz_atan_L1_shots1024_seed42_scores.csv",
        ROOT / "Experiments/results/water_quantum_gamma_grid/scores.csv",
    ]
    for index, path in enumerate(quantum_paths):
        q = pd.read_csv(path).set_index("molecule")
        row = q.loc["Water"]
        summary.append({"model": "ZZ_map/arctan/L1", "gamma": row.gamma,
                        "C": row.C, "epsilon": row.epsilon, "water_cv_r2": row.cv_r2,
                        "water_test_r2": row.test_r2,
                        "mean_transfer_test_r2": float(q.loc[MOLS[1:], "test_r2"].mean()),
                        "gamma_selected_by_water_cv": bool(index == 1)})
    df = pd.DataFrame(summary)
    df.to_csv(OUT / "summary.csv", index=False)

    table = write_table(df)

    inputs = [cv_path, Path(__file__), ROOT / "Experiments/qk_common.py", *quantum_paths]
    for mol in MOLS:
        base = ROOT / "data/training/STO-3G" / mol / "scaled"
        inputs.extend(base / name for name in ["full_feature_test.bin", "feature_scaler.bin", "t2_scaler.bin"])
    inputs.append(ROOT / "data/training/STO-3G/Water/scaled/full_feature_train.bin")
    manifest = {
        "purpose": "Water bandwidth comparison on Figure 5 target test splits",
        "n_train": len(y), "source": "Water", "basis": "STO-3G",
        "cv": "Saved KFold(5, shuffle=False) amplitude-fold scores; scalers fitted on water training data",
        "C_grid": sorted(cv.param_C.unique().tolist()),
        "epsilon_grid": sorted(cv.param_epsilon.unique().tolist()),
        "gamma_grid": sorted(cv.gamma.unique().tolist()),
        "C_epsilon_selection": "Highest water CV score independently at each gamma",
        "classical_source_selected_gamma": float(source_winner.gamma),
        "transfer_population": "Test split of each of six targets; unweighted mean of six R2 scores",
        "posthoc_scope": "Choosing gamma by transfer scores uses target labels",
        "quantum_scope": "One seed for the retrospectively selected ZZFeatureMap/arctan/L1 architecture",
        "figure5_baseline_max_score_error": error,
        "versions": {"numpy": np.__version__, "sklearn": sklearn.__version__},
        "inputs": {str(p.relative_to(ROOT)): digest(p) for p in inputs},
        "outputs": {str(p.relative_to(ROOT)): digest(p)
                    for p in [OUT / "summary.csv", OUT / "classical_test_scores.csv", table]},
        "artifacts": {str(p.relative_to(ROOT)): digest(p) for p in sorted(ARTIFACTS.iterdir())
                      if p.suffix in {".npz", ".joblib"}},
    }
    (ARTIFACTS / "run_manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    settings = {k: v for k, v in manifest.items() if k not in {"inputs", "outputs", "artifacts"}}
    (OUT / "manifest.json").write_text(json.dumps(settings, indent=2) + "\n")
    print(df.to_string(index=False), flush=True)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--table-only", action="store_true", help="export Table S8 from saved scores without fitting models")
    args = parser.parse_args()
    if args.table_only:
        print(write_table(pd.read_csv(OUT / "summary.csv")))
    else:
        main()
